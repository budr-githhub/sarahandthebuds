import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
export function validate(events, venues) {
 const errors=[];
 const date=v=>typeof v==='string' && /^\d{4}-\d{2}-\d{2}$/.test(v) && !Number.isNaN(Date.parse(v)) && new Date(v).toISOString().slice(0,10)===v;
 const time=v=>typeof v==='string' && /^([01]\d|2[0-3]):[0-5]\d$/.test(v);
 const url=v=>{try{return ['http:','https:'].includes(new URL(v).protocol)}catch{return false}};
 if(!Array.isArray(events))return ['Events must be an array.'];
 for(const [id,v] of Object.entries(venues)) {
  if(!v.name?.trim()||!v.city?.trim())errors.push(`Venue ${id}: name and city are required.`);
  if(v.url&&!url(v.url))errors.push(`Venue ${id}: invalid website URL.`);
 }
 events.forEach((e,i)=>{
  const label=e.name || `Show ${i+1}`;
  const fail=m=>errors.push(`${label}: ${m}`);
  if(!['draft','published','cancelled'].includes(e.status))fail('choose a publication status.');
  if(e.status==='draft')return;
  if(!e.name?.trim())fail('event name is required.');
  if(!date(e.start)||e.end&&!date(e.end))fail('use a valid date in YYYY-MM-DD format.');
  if(!time(e.startTime)||!time(e.endTime))fail('use 24-hour times, HH:MM.');
  if(date(e.start)&&time(e.startTime)&&time(e.endTime)&&`${e.end||e.start}T${e.endTime}`<=`${e.start}T${e.startTime}`)fail('end must be after start; use an end date for overnight events.');
  if(!Object.hasOwn(venues,e.venueId))fail('choose a known venue.');
  if(!['full-band','duo','solo','other'].includes(e.act))fail('choose a performing act.');
  if(e.act==='other'&&!e.performers?.trim())fail('enter the other act / performer names.');
  if(e.url&&!url(e.url))fail('event URL must begin with http:// or https://.');
 });
 return errors;
}
export function calendarDoc(events,venues){
 const safe=v=>String(v??'').replaceAll('|','\\|').replace(/[\r\n]+/g,' ');
 const labels={'full-band':'Sarah & the Buds — full band',duo:'Sarah & Bud — acoustic duo',solo:'Bud Ratliff — solo'};
 let out='# Calendar inventory\n\nGenerated from `src/data/events.json` and `src/data/venues.json`. Do not edit this file manually. All times are Eastern (24-hour). This records saved content, not proof of successful deployment. Drafts are excluded; they are still stored in the public GitHub repository.\n\n| Date | Time | Event | Act | Venue / address | Status | Details | Links |\n|---|---|---|---|---|---|---|---|\n';
 for(const e of [...events].filter(e=>e.status!=='draft').sort((a,b)=>a.start.localeCompare(b.start))){const v=venues[e.venueId];out+='| '+[e.start+(e.end?'–'+e.end:''),`${e.startTime}–${e.endTime}`,e.name,labels[e.act]||e.performers,`${v.name}: ${v.address||v.city}`,e.status,[e.notes,e.admission,e.location].filter(Boolean).join(' · '),[v.url,e.url].filter(Boolean).join(' · ')].map(safe).join(' | ')+' |\n';}
 return out;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const events=JSON.parse(readFileSync('src/data/events.json','utf8'));
 const venues=JSON.parse(readFileSync('src/data/venues.json','utf8'));
 const errors=validate(events,venues);
 if(errors.length){console.error(errors.join('\n'));process.exit(1)}
 if(process.argv.includes('--write')){mkdirSync('reports',{recursive:true});writeFileSync('reports/calendar-inventory.md',calendarDoc(events,venues));}
 console.log(`Calendar valid: ${events.length} records.`);
}
